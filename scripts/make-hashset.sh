#!/bin/bash
# make-hashset.sh - produce a hash set for the build source, so anyone can
# verify that the build system they received is exactly the one that produced
# a release. Written for examiners: coreutils-verifiable sets plus a
# hashdeep-format file, and a dedicated record for build.sh.
#
# Output (hashes/):
#   SHA256SUMS, SHA1SUMS, MD5SUMS   verify with:  sha256sum -c hashes/SHA256SUMS
#   hashdeep.txt                    HASHDEEP-1.0 format (size,md5,sha1,sha256,file)
#                                   audit with:   hashdeep -r -a -k hashes/hashdeep.txt .
#   build.sh.txt                    size, dates and MD5/SHA-1/SHA-256/SHA-512 of build.sh
#   MANIFEST.txt                    what was hashed, when, from which commit
#
# Everything under the project is hashed except build output (work/ iso/ cache/),
# git metadata, and the hashes/ directory itself.
#
#   ./scripts/make-hashset.sh
set -euo pipefail
cd "$(dirname "$0")/.." || exit 2
OUT=hashes
rm -rf "$OUT"; mkdir -p "$OUT"

# stable, sorted, NUL-safe list of files to hash (relative paths, no leading ./)
list_files() {
    find . -type f \
        ! -path './work/*' ! -path './iso/*' ! -path './cache/*' \
        ! -path './.git/*' ! -path "./$OUT/*" \
        ! -name '*.iso' ! -name '*.log' \
        -print0 | sed -z 's|^\./||' | sort -z
}

n=$(list_files | tr -cd '\0' | wc -c)
echo "hashing $n files ..."

list_files | xargs -0 sha256sum > "$OUT/SHA256SUMS"
list_files | xargs -0 sha1sum   > "$OUT/SHA1SUMS"
list_files | xargs -0 md5sum    > "$OUT/MD5SUMS"

# hashdeep format: size,md5,sha1,sha256,filename
{
    echo '%%%% HASHDEEP-1.0'
    echo '%%%% size,md5,sha1,sha256,filename'
    echo "## Invoked from: $(pwd)"
    echo '## $ hashdeep -c md5,sha1,sha256 -r . (equivalent; generated by scripts/make-hashset.sh)'
    echo '## '
    list_files | while IFS= read -r -d '' f; do
        printf '%s,%s,%s,%s,%s\n' \
            "$(stat -c %s "$f")" \
            "$(md5sum    "$f" | cut -d' ' -f1)" \
            "$(sha1sum   "$f" | cut -d' ' -f1)" \
            "$(sha256sum "$f" | cut -d' ' -f1)" \
            "$f"
    done
} > "$OUT/hashdeep.txt"

# dedicated record for the build script itself
{
    echo "CFL Forensics - hash record for build.sh"
    echo "========================================"
    echo "file      : build.sh"
    echo "size      : $(stat -c %s build.sh) bytes"
    echo "modified  : $(date -u -r build.sh '+%Y-%m-%d %H:%M:%S UTC')"
    echo "hashed    : $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
    echo "MD5       : $(md5sum    build.sh | cut -d' ' -f1)"
    echo "SHA-1     : $(sha1sum   build.sh | cut -d' ' -f1)"
    echo "SHA-256   : $(sha256sum build.sh | cut -d' ' -f1)"
    echo "SHA-512   : $(sha512sum build.sh | cut -d' ' -f1)"
    echo
    echo "verify    : sha256sum build.sh   (compare to SHA-256 above)"
} > "$OUT/build.sh.txt"

# manifest of the run
{
    echo "CFL Forensics build-source hash set"
    echo "generated : $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
    echo "files     : $n"
    if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        echo "commit    : $(git rev-parse HEAD 2>/dev/null) $(git diff --quiet 2>/dev/null && echo '(clean)' || echo '(with local changes)')"
    else
        echo "commit    : (not a git checkout)"
    fi
    echo "version   : $(grep -oE 'CFL_VERSION:=[^}]+' cfl-build.conf | cut -d= -f2)"
    echo "excluded  : work/ iso/ cache/ .git/ $OUT/ *.iso *.log"
    echo
    echo "verify all files:   sha256sum -c $OUT/SHA256SUMS"
    echo "audit (hashdeep):   hashdeep -r -a -k $OUT/hashdeep.txt ."
} > "$OUT/MANIFEST.txt"

echo "wrote $OUT/: SHA256SUMS SHA1SUMS MD5SUMS hashdeep.txt build.sh.txt MANIFEST.txt"
echo "build.sh SHA-256: $(sha256sum build.sh | cut -d' ' -f1)"
